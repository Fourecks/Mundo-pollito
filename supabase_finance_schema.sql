-- SCRIPT COMPLETO DE TABLAS Y CAMPOS PARA EL MÓDULO DE FINANZAS EN SUPABASE

-- 1. Cuentas (Bancos, Efectivo, Débito, Crédito)
CREATE TABLE IF NOT EXISTS public.finance_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    name TEXT NOT NULL,
    type TEXT NOT NULL DEFAULT 'bank', -- 'bank', 'wallet', 'cash', 'debit', 'credit'
    balance_cents BIGINT NOT NULL DEFAULT 0,
    credit_limit_cents BIGINT DEFAULT 0,
    cutoff_day INT DEFAULT 15,
    due_day INT DEFAULT 5,
    card_number_last4 TEXT,
    card_color TEXT DEFAULT 'slate',
    currency TEXT NOT NULL DEFAULT 'USD',
    is_archived BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Agregar columnas en caso de que la tabla ya exista previamente:
ALTER TABLE public.finance_accounts ADD COLUMN IF NOT EXISTS credit_limit_cents BIGINT DEFAULT 0;
ALTER TABLE public.finance_accounts ADD COLUMN IF NOT EXISTS cutoff_day INT DEFAULT 15;
ALTER TABLE public.finance_accounts ADD COLUMN IF NOT EXISTS due_day INT DEFAULT 5;
ALTER TABLE public.finance_accounts ADD COLUMN IF NOT EXISTS card_number_last4 TEXT;
ALTER TABLE public.finance_accounts ADD COLUMN IF NOT EXISTS card_color TEXT DEFAULT 'slate';

ALTER TABLE public.finance_accounts ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "finance_accounts_all" ON public.finance_accounts;
CREATE POLICY "finance_accounts_all" ON public.finance_accounts FOR ALL USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());

