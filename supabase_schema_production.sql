-- 9. POLÍTICAS DE SEGURIDAD
CREATE POLICY "profiles_policy" ON public.profiles FOR ALL USING (auth.uid() = id) WITH CHECK (auth.uid() = id);
CREATE POLICY "folders_policy" ON public.folders FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "notes_policy" ON public.notes FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "quick_notes_policy" ON public.quick_notes FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "habits_policy" ON public.habits FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "habit_records_policy" ON public.habit_records FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "playlists_policy" ON public.playlists FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "user_backgrounds_policy" ON public.user_backgrounds FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "ai_conversations_policy" ON public.ai_conversations FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

CREATE POLICY "projects_policy" ON public.projects FOR ALL USING (
    auth.uid() = user_id 
    OR members @> jsonb_build_array(jsonb_build_object('id', auth.uid()::text))
    OR members @> jsonb_build_array(jsonb_build_object('email', (auth.jwt() ->> 'email')))
) WITH CHECK (
    auth.uid() = user_id 
    OR members @> jsonb_build_array(jsonb_build_object('id', auth.uid()::text))
    OR members @> jsonb_build_array(jsonb_build_object('email', (auth.jwt() ->> 'email')))
);

CREATE POLICY "invitations_policy" ON public.project_invitations FOR ALL USING (
    auth.uid() = inviter_id 
    OR auth.uid() = sender_id 
    OR lower(invitee_email) = lower(auth.jwt() ->> 'email')
    OR lower(receiver_email) = lower(auth.jwt() ->> 'email')
) WITH CHECK (
    auth.uid() = inviter_id 
    OR auth.uid() = sender_id 
    OR lower(invitee_email) = lower(auth.jwt() ->> 'email')
    OR lower(receiver_email) = lower(auth.jwt() ->> 'email')
);

CREATE POLICY "todos_policy" ON public.todos FOR ALL USING (
    auth.uid() = user_id 
    OR (project_id IS NOT NULL AND EXISTS (
        SELECT 1 FROM public.projects p 
        WHERE p.id = project_id 
        AND (
            p.user_id = auth.uid() 
            OR p.members @> jsonb_build_array(jsonb_build_object('id', auth.uid()::text))
            OR p.members @> jsonb_build_array(jsonb_build_object('email', (auth.jwt() ->> 'email')))
        )
    ))
) WITH CHECK (
    auth.uid() = user_id 
    OR (project_id IS NOT NULL AND EXISTS (
        SELECT 1 FROM public.projects p 
        WHERE p.id = project_id 
        AND (
            p.user_id = auth.uid() 
            OR p.members @> jsonb_build_array(jsonb_build_object('id', auth.uid()::text))
            OR p.members @> jsonb_build_array(jsonb_build_object('email', (auth.jwt() ->> 'email')))
        )
    ))
);

CREATE POLICY "subtasks_policy" ON public.subtasks FOR ALL USING (
    EXISTS (SELECT 1 FROM public.todos t WHERE t.id = todo_id AND t.user_id = auth.uid())
) WITH CHECK (
    EXISTS (SELECT 1 FROM public.todos t WHERE t.id = todo_id AND t.user_id = auth.uid())
);

-- 10. TRIGGER PARA CREACIÓN AUTOMÁTICA DE PERFIL
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger AS $$
BEGIN
  INSERT INTO public.profiles (id, created_at, updated_at)
  VALUES (new.id, NOW(), NOW())
  ON CONFLICT (id) DO NOTHING;
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

